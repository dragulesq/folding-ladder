#!/usr/bin/env python3
"""Join the B3 FeatureScript files into one Feature Studio that needs no imports.

Usage: python3 tools/build_all_in_one.py
Writes onshape/B3_AllInOne.fs. Run it after changing any file in onshape/.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "onshape"
OUT = SRC / "B3_AllInOne.fs"

ORDER = [
    "B3_Parameters.fs",
    "B3_Lib.fs",
    "B3_Reference.fs",
    "B3_Treads.fs",
    "B3_Brackets.fs",
    "B3_OuterRail.fs",
    "B3_StepClip.fs",
    "B3_PivotHardware.fs",
    "B3_FrontAngle.fs",
    "B3_StepLedge.fs",
    "B3_HookOnStep.fs",
]

HEADER = re.compile(r'^(FeatureScript \d+;|import\(path : "onshape/std/common\.fs".*\);)\s*$')
IMPORT_BLOCK = re.compile(r"// <B3-IMPORT>.*?// </B3-IMPORT>\n", re.S)


def main():
    first = (SRC / ORDER[0]).read_text().splitlines()[:2]
    parts = [
        "\n".join(first),
        "",
        "// B3 folding bed stair: every feature in one Feature Studio.",
        "// Generated by tools/build_all_in_one.py from the files in onshape/. Edit those, then rebuild.",
    ]
    for name in ORDER:
        text = IMPORT_BLOCK.sub("", (SRC / name).read_text())
        body = [line for line in text.splitlines() if not HEADER.match(line)]
        parts += ["", "// " + "=" * 75, f"// {name}", "// " + "=" * 75, "\n".join(body).strip("\n")]
    OUT.write_text("\n".join(parts) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
